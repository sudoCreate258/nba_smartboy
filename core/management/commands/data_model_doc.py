INTRO = """\
# Data model

<!-- Generated by `python manage.py data_model_doc` from core/models.py and ledger/models.py. Do not edit by hand;
     run the command after changing a model. tests/test_docs.py fails when this file is stale. -->

This describes what the code stores today. All times are stored in UTC; offset-less input is read
in the contributor's time zone (`Contributor.timezone`), and local times that are ambiguous or
skipped by a daylight-saving change are rejected on import.

## Records, CIDs and corrections

- Every record type below is a `ProvenancedRecord`: it has a `contributor` and a `cid`, and it is
  immutable once saved (`save()` on a stored record, queryset `update()` and `delete()` all raise
  `ImmutableRecordError`).
- **CID** = CIDv1, raw codec (0x55), sha2-256, base32 lower case without padding (`bafkrei...`),
  over canonical JSON bytes: `{"contributor": <handle>, "fields": {...}, "kind": <record kind>}`
  with sorted keys, compact separators and UTF-8 (`nymbus/provenance.py`).
- **Fields in the CID:** every concrete field except `id`, `cid`, `contributor` (the handle is in
  the envelope) and `created_at`. Values are coerced to the field type first; decimals are
  quantized to the field's places, so `97.8`, `"97.8"` and `Decimal("97.80")` hash the same;
  datetimes are hashed as UTC ISO strings; naive datetimes are rejected.
- **`OMIT_IF_NULL`:** a field listed there is left out of the canonical content while it is null,
  so records stored before the field existed keep their CID. Every nullable field added after
  records exist must be listed (standing rule, `.kiro/steering/nymbus.md`). Pinned CIDs in the
  tests guard this.
- **Corrections** never edit a record: a new record is saved and a `Supersession` event
  (`old_cid -> new_cid`, same kind and contributor) is appended. A record is *current* when the
  latest Supersession touching its CID points to it, or none does, so a revert (A -> B -> A)
  makes A current again without a new row. Records that point to another record by CID
  (Reset -> ProbeSession, TrainingSet -> TrainingSession) follow the correction chain
  (`core.models.Lineage`).
- Identical content gives the same CID, so re-importing a file is a no-op.

## Export format (nymbus-jsonl, version 1)

First draft of the Nymbus interchange contract. `manage.py export_my_data` and the app's
"Download my data" write one JSON object per line (UTF-8), in the order things were created:

- Line 1: `{"type": "export", "format": "nymbus-jsonl", "version": 1, "contributor": <handle>,
  "timezone": <IANA zone>, "exported_at": <UTC ISO>}`
- Record: `{"type": "record", "kind": <record kind>, "cid": ..., "contributor": <handle>,
  "fields": {...}, "created_at": <UTC ISO>}`. `fields` is exactly the content the CID is computed
  over (OMIT_IF_NULL fields left out while null; datetimes as UTC ISO strings, decimals as strings),
  so `CID(canonical(kind, contributor, fields)) == cid` can be checked from the line alone.
- Correction: `{"type": "supersession", "old_cid": ..., "new_cid": ..., "reason": ..., "created_at": ...}`

`manage.py import_my_data <file>` replays the lines into a database with no records for that
contributor, checks every CID (against the line and against the stored record) and rolls the
whole file back on any error. `created_at` is informational; restored rows get the import time.
The ledger (M5: `grant`, `revocation`, `access_event`) is exported as ordinary record lines; the
import replays each access event against the one before it and checks the whole hash chain.
Not included: Django users, ProbeBaseline settings, module on/off settings.

## Deposit statement (nymbus-statement-jsonl, version 1)

Per local month: line 1 `{"type": "statement", "format": "nymbus-statement-jsonl", "version": 1,
"contributor", "timezone", "month": "YYYY-MM", "unit": "simulated credits", "cid"}`, then
`{"type": "row", "category", "recipient", "purpose", "reads", "records_accessed",
"distinct_records", "units"}` per (category, recipient, purpose) and `{"type": "total", "category",
"reads", "records_accessed", "units"}` per category. `cid` is the CIDv1 of
`canonical("deposit_statement", contributor, {"month", "timezone", "unit", "rows"})` (rows without
`type`). There is no currency field: units are simulated credits.
"""


def _type(field):
    if isinstance(field, models.ForeignKey):
        return f"FK -> {field.related_model.__name__}"
    if isinstance(field, models.DecimalField):
        return f"decimal({field.max_digits},{field.decimal_places})"
    if isinstance(field, models.CharField):
        return f"text (max {field.max_length})"
    return {
        "DateTimeField": "datetime (UTC)", "DateField": "date", "TextField": "text",
        "BooleanField": "bool", "PositiveSmallIntegerField": "int >= 0", "BigAutoField": "id",
        "PositiveIntegerField": "int >= 0", "JSONField": "JSON",
    }.get(field.get_internal_type(), field.get_internal_type())


def _bounds(field):
    # Only validators declared in the model (`_validators`), not the database integer ranges
    # Django adds on its own.
    declared = list(field._validators)
    lo = [v.limit_value for v in declared if isinstance(v, MinValueValidator)]
    hi = [v.limit_value for v in declared if isinstance(v, MaxValueValidator)]
    parts = []
    if lo:
        parts.append(f">= {lo[0]}")
    if hi:
        parts.append(f"<= {hi[0]}")
    if field.choices:
        parts.append("one of: " + ", ".join(f"`{value}`" for value, _ in field.choices))
    return "; ".join(parts)


def _required(field):
    if field.primary_key or field.name in {"cid", "created_at"}:
        return "auto"
    if isinstance(field, models.BooleanField) or field.has_default():
        return f"default `{field.get_default()}`" if not callable(field.default) else "default now"
    if field.null or field.blank:
        return "optional"
    return "required"


def _table(model):
    omit = set(getattr(model, "OMIT_IF_NULL", ()))
    rows = ["| field | type | required | bounds / choices | notes |", "|---|---|---|---|---|"]
    for field in model._meta.concrete_fields:
        notes = []
        if field.name in omit:
            notes.append("OMIT_IF_NULL")
        if field.help_text:
            notes.append(str(field.help_text))
        rows.append(f"| `{field.name}` | {_type(field)} | {_required(field)} | {_bounds(field)} | {' '.join(notes)} |")
    return rows


def render():
    lines = [INTRO.rstrip(), "", "## Record types", ""]
    for model in RECORDS:
        assert issubclass(model, ProvenancedRecord)
        lines.append(f"### {model.__name__} (`{model.record_kind}`)")
        lines.append("")
        doc = (model.__doc__ or "").strip().split("\n\n")[0].replace("\n", " ")
        if doc and not doc.startswith(model.__name__ + "("):
            lines += [" ".join(doc.split()), ""]
        lines += _table(model)
        rules = MODEL_RULES.get(model, [])
        if rules:
            lines += ["", "Rules:"] + [f"- {r}" for r in rules]
        lines.append("")
    lines += ["## Other tables (no CID)", ""]
    for model in OTHER:
        lines.append(f"### {model.__name__}")
        lines.append("")
        doc = (model.__doc__ or "").strip().split("\n\n")[0].replace("\n", " ")
        if doc and not doc.startswith(model.__name__ + "("):
            lines += [" ".join(doc.split()), ""]
        lines += _table(model)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


class Command(BaseCommand):
    help = "Write docs/DATA_MODEL.md from the models (or check that it is up to date)."

    def add_arguments(self, parser):
        parser.add_argument("--check", action="store_true", help="fail if docs/DATA_MODEL.md is out of date")

    def handle(self, *args, check, **options):
        text = render()
        if check:
            current = PATH.read_text(encoding="utf-8") if PATH.exists() else ""
            if current != text:
                raise CommandError("docs/DATA_MODEL.md is out of date; run `python manage.py data_model_doc`.")
            self.stdout.write("docs/DATA_MODEL.md is up to date.")
            return
        PATH.write_text(text, encoding="utf-8", newline="\n")
        self.stdout.write(f"Wrote {PATH}")
