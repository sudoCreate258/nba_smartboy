"""Summarise results/e1.csv into results/summary.md with text bar charts (stdlib only).

    python experiments/mininet-fl/summarize.py
"""
import csv
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SRC, OUT = os.path.join(HERE, "results", "e1.csv"), os.path.join(HERE, "results", "summary.md")


def bar(value, top, width=30):
    return "#" * max(1, round(width * value / top)) if top else ""


def main():
    rows = list(csv.DictReader(open(SRC, encoding="utf-8")))
    lines = ["# E1 results (generated by summarize.py)", "",
             f"Switch: {rows[0]['switch']}; model {int(rows[0]['model_bytes']) / 1e6:.0f} MB float32; "
             f"{rows[0]['rounds']} rounds per run; numbers per round.", ""]
    lines += ["| clients | pattern | Mbit/s | latency ms | MB on the wire | MB through server link | s/round |",
              "|---:|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        n = int(r["rounds"])
        lines.append(f"| {r['clients']} | {r['pattern']} | {r['bw_mbit']} | {r['latency_ms']} | "
                     f"{int(r['bytes_on_wire']) / n / 1e6:.1f} | {int(r['server_link_bytes']) / n / 1e6:.1f} | "
                     f"{float(r['round_s_mean']):.2f} |")
    by = defaultdict(dict)
    for r in rows:
        by[(r["clients"], r["bw_mbit"], r["latency_ms"])][r["pattern"]] = r
    for (clients, bw, lat), pats in sorted(by.items(), key=lambda k: (int(k[0][0]), int(k[0][1]), int(k[0][2]))):
        lines += ["", f"### {clients} clients, {bw} Mbit/s, {lat} ms", "", "```text"]
        top_t = max(float(p["round_s_mean"]) for p in pats.values())
        top_b = max(int(p["server_link_bytes"]) for p in pats.values())
        for name, p in pats.items():
            t, b = float(p["round_s_mean"]), int(p["server_link_bytes"]) / int(p["rounds"])
            lines.append(f"{name:<10} time {t:6.2f} s {bar(t, top_t):<30}  server link {b / 1e6:6.1f} MB "
                         f"{bar(int(p['server_link_bytes']), top_b)}")
        lines.append("```")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
