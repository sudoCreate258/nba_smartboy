"""Test vectors for docs/PORTING.md (M6 R9). Plain Python: only nymbus/, no Django.

    python tools/porting_vectors.py    # print the vector section of PORTING.md

tests/test_porting.py checks that PORTING.md carries exactly this output, and that the Django
models compute the same CIDs, so the document cannot drift from the code.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from nymbus import ledger  # noqa: E402
from nymbus.provenance import canonical_bytes, compute_cid  # noqa: E402

CONTRIBUTOR = "mike"

# Canonical content exactly as it is hashed (normalize_fields output): datetimes as UTC ISO strings,
# decimals as strings, OMIT_IF_NULL fields left out while null.
RECORDS = [
    ("daily_snapshot", {"date": "2026-11-10", "sleep_score": 80, "bedtime": None, "wake_time": "2026-11-10T12:00:00+00:00",
                        "sleep_duration_min": 450, "resting_hr_sleep": 52, "hrv": 61, "spo2": "96.5",
                        "weight_kg": None, "body_fat_pct": None, "skeletal_muscle_kg": None, "bmr_kcal": None,
                        "bia_timing": "unknown", "source": "manual", "notes": ""}),
    ("probe_session", {"started_at": "2026-11-10T13:50:00+00:00", "kind": "mini_puzzle", "time_control": None,
                       "n_items": 5, "accuracy_pct": "80.0", "median_solve_s": "12.5", "blunders": 1,
                       "late_blunders": 0, "fast_blunders": 1, "opponent_rating": None, "own_rating": None,
                       "move_time_cv": "0.40", "location": "office", "notes": ""}),
    ("weekly_check", {"week_start": "2026-11-09", "instrument": "OLBI", "score": "2.40", "scale_max": "4.00",
                      "notes": ""}),
]


def record_vectors():
    out = []
    for kind, fields in RECORDS:
        data = canonical_bytes(kind, CONTRIBUTOR, fields)
        out.append({"kind": kind, "fields": fields, "canonical": data.decode("utf-8"), "cid": compute_cid(data)})
    return out


GRANT = {"category": "probes", "recipient": "sim-research-partner", "purpose": "fatigue study",
         "start": "2026-11-10T14:00:00+00:00", "end": None}


def chain_vectors():
    """A grant and three access events reading the probe record above; the head after them."""
    grant_cid = compute_cid(canonical_bytes("grant", CONTRIBUTOR, GRANT))
    probe_cid = record_vectors()[1]["cid"]
    events, prev = [], ledger.GENESIS
    for seq, (at, cids) in enumerate([("2026-11-10T15:00:00+00:00", [probe_cid]),
                                      ("2026-11-11T15:00:00+00:00", [probe_cid]),
                                      ("2026-11-12T15:00:00+00:00", [])], start=1):
        fields = {"seq": seq, "at": at, "grant_cid": grant_cid, "recipient": GRANT["recipient"],
                  "category": GRANT["category"], "purpose": GRANT["purpose"], "record_cids": cids,
                  "units": ledger.units_for(cids), "prev_hash": prev}
        data = canonical_bytes("access_event", CONTRIBUTOR, fields)
        events.append({"fields": fields, "canonical": data.decode("utf-8"), "cid": compute_cid(data),
                       "sha256": ledger.digest(data)})
        prev = ledger.digest(data)
    head = {"events": len(events), "last_hash": prev}
    return {"grant": {"fields": GRANT, "cid": grant_cid}, "events": events, "head": head}


def markdown():
    lines = ["<!-- vectors: generated by `python tools/porting_vectors.py`; tests/test_porting.py checks them -->", ""]
    lines += ["### Records", ""]
    for v in record_vectors():
        lines += [f"**{v['kind']}** (contributor `{CONTRIBUTOR}`)", "", "Canonical bytes (UTF-8):", "", "```json",
                  v["canonical"], "```", "", f"CID: `{v['cid']}`", ""]
    c = chain_vectors()
    lines += ["### Grant and a 3-event chain", "", "Grant canonical bytes:", "", "```json",
              canonical_bytes("grant", CONTRIBUTOR, c["grant"]["fields"]).decode("utf-8"), "```", "",
              f"Grant CID: `{c['grant']['cid']}`", ""]
    for e in c["events"]:
        lines += [f"Event {e['fields']['seq']} canonical bytes:", "", "```json", e["canonical"], "```", "",
                  f"SHA-256: `{e['sha256']}`  ", f"CID: `{e['cid']}`", ""]
    lines += ["Head after the three events:", "", "```json", json.dumps(c["head"], sort_keys=True), "```",
              "<!-- /vectors -->"]
    return "\n".join(lines)


START, END = "<!-- vectors:", "<!-- /vectors -->"
DOC = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "PORTING.md")


def write():
    """Replace the vector block in docs/PORTING.md (between the markers) with the current vectors."""
    with open(DOC, encoding="utf-8") as fh:
        text = fh.read()
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(head + markdown() + tail)


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        write()
    else:
        print(markdown())
